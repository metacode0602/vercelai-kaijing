import {
  tenantRegionGpuConsumptionDaily,
  tenantRegionGpuConsumptionMonthly,
} from '@workspace/db/schema'
import type { TenantRegionGpuConsumptionListItem } from './types'

export function mapDailyRow(
  row: typeof tenantRegionGpuConsumptionDaily.$inferSelect,
): TenantRegionGpuConsumptionListItem {
  return {
    id: row.id,
    usageDate: row.usageDate,
    usageMonth: row.usageMonth,
    tenantPlatformId: row.tenantPlatformId,
    tenantId: row.tenantId,
    tenantName: row.tenantName,
    customerFullName: row.customerFullName,
    projectName: row.projectName,
    accountManagerName: row.accountManagerName,
    customerIncentiveLabel: row.customerIncentiveLabel,
    incentiveStartDate: row.incentiveStartDate,
    regionCode: row.regionCode,
    gpuModel: row.gpuModel,
    productLine: row.productLine,
    source: row.source,
    dataCenterId: row.dataCenterId,
    dataCenterName: row.dataCenterName,
    gpuCardTypeId: row.gpuCardTypeId,
    gpuCardTypeName: row.gpuCardTypeName,
    pricingMode: row.pricingMode,
    listPricePerHour: row.listPricePerHour,
    unitPricePerHour: row.unitPricePerHour,
    revenueSharePercent: row.revenueSharePercent,
    pricingResolveStatus: row.pricingResolveStatus,
    baseValue: row.baseValue,
    totalConsumption: row.totalConsumption,
    voucherConsumption: row.voucherConsumption,
    balanceConsumption: row.balanceConsumption,
    totalCardHours: row.totalCardHours,
    voucherCardHours: row.voucherCardHours,
    balanceCardHours: row.balanceCardHours,
    enrichmentBindingSource: row.enrichmentBindingSource,
    hasAmortization: false,
  }
}

